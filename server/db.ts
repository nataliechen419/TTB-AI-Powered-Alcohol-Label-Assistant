export const applications = new Map<string, Application>(seed.map(a => [a.id, a]))

export function listApplications(): Application[] {
  return [...applications.values()].sort((a, b) => (a.submitted < b.submitted ? 1 : -1))
}

export function getApplication(id: string): Application | undefined {
  return applications.get(id)
}
