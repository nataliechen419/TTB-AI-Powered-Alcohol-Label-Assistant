// In-memory prototype "database". Resets on server restart.

export type FieldKey =
  | 'brandName'
  | 'beverageType'
  | 'classType'
  | 'abv'
  | 'netContents'
  | 'bottlerAddress'
  | 'countryOfOrigin'
  | 'governmentWarning'

export const FIELD_LABELS: Record<FieldKey, string> = {
  brandName: 'Brand Name',
  beverageType: 'Beverage Type',
  classType: 'Class / Type Designation',
  abv: 'Alcohol Content (ABV)',
  netContents: 'Net Contents',
  bottlerAddress: 'Name & Address of Bottler/Producer',
  countryOfOrigin: 'Country of Origin',
  governmentWarning: 'Government Health Warning Statement',
}

export interface ApplicationData {
  brandName: string
  /** Broad federal category — "Wine", "Distilled Spirits", or "Malt
   * Beverage" — as distinct from the more specific classType designation
   * (e.g. "Straight Bourbon Whiskey"). Compared like any other field. */
  beverageType: string
  classType: string
  abv: string
  netContents: string
  bottlerAddress: string
  /** null for domestic products — this field only applies to imports. */
  countryOfOrigin: string | null
  governmentWarning: string
}

export type AppStatus = 'Pending' | 'Needs Review' | 'Approved' | 'Flagged'

/** 'onLabel' is a neutral, non-judged state used for fields (currently just
 * classType) where we only confirm presence on the label rather than
 * compare wording against the application — see server/compare.ts.
 * 'missing' is distinct from both 'mismatch' (a value was detected and it
 * disagrees with the application) and 'unreadable' (a value is there but
 * image quality prevents reading it) — it means the field is genuinely not
 * printed on the label at all. Kept as its own status rather than folded
 * into 'mismatch' so the UI doesn't imply a wrong value was found when
 * really nothing was found. */
export type FieldStatus = 'match' | 'variance' | 'mismatch' | 'unreadable' | 'onLabel' | 'missing'

export interface FieldResult {
  key: FieldKey
  label: string
  appValue: string
  detected: string
  status: FieldStatus
  highStakes?: boolean
  note?: string
}

export interface ReviewResult {
  fields: FieldResult[]
  imageQuality: 'clear' | 'poor'
  qualityNote?: string
  reviewedAt: string
  /** True when this review was generated by the local mock extractor
   * instead of a live Claude API call (see server/mock.ts). */
  mockMode?: boolean
  /** How long the extraction call itself took, in ms — shown to the
   * reviewer so analysis speed isn't a black box. */
  durationMs?: number
}

export interface Decision {
  action: 'approve' | 'reject' | 'flag'
  comment: string
  at: string
}

export interface Application {
  id: string
  brand: string
  type: string
  submitted: string
  status: AppStatus
  flagged: number
  applicationData: ApplicationData
  labelImageDataUrl?: string
  review?: ReviewResult
  decision?: Decision
}

